"""Run the cleaning pipeline and write docs/DATA_QUALITY.md (before/after evidence).

Run:  python scripts/clean_data.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src import data_prep  # noqa: E402

out = data_prep.run()
for name, df in out.items():
    print(f"data/cleaned/{name}.csv: {len(df)} rows")


def md_table(df) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v).replace("|", "\\|") for v in r) + " |")
    return "\n".join(lines)


q_cat = out["quarantine_supplier_catalog"][["supplier_id", "sku", "product_id", "lead_time", "moq", "reason"]]
q_ord = out["quarantine_orders"][["order_id", "order_date", "product_id", "reason"]]
doc = ["# Data quality evidence", "",
       "Generated by `python scripts/clean_data.py` from `data/raw/` and `data/generated/`. "
       "Raw files are never modified; outputs are in `data/cleaned/`.", "",
       "## Issues: detection, rule, before -> after", "", md_table(out["dq_report"]), "",
       f"## Correction log ({len(out['correction_log'])} changes)", "", md_table(out["correction_log"]), "",
       "## Quarantine: supplier catalog (needs a buyer)", "", md_table(q_cat), "",
       "## Quarantine: orders (excluded from demand)", "", md_table(q_ord), ""]
(ROOT / "docs" / "DATA_QUALITY.md").write_text("\n".join(doc), encoding="utf-8")
print("docs/DATA_QUALITY.md written")
